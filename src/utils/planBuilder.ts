import { DayPlan } from '../types';
import { resolveReflection, shortQuote, UNKNOWN } from './reflectionContext';

type Task = [string, string, string];

export function makeSevenDayPlan(context: ReturnType<typeof resolveReflection>) {
  const { inputs, concern, desired } = context;
  const text = `${inputs.dilemma} ${desired}`;
  const goal = desired === UNKNOWN ? '이번 고민에서 확인하고 싶은 것' : shortQuote(desired, 100);
  const worry = concern === UNKNOWN ? '선택을 망설이게 하는 조건' : shortQuote(concern, 90);
  const availableMinutes = inputs.constraints.energyOrPersonal.match(/(\d+)\s*분/)?.[1]
    || text.match(/(?:하루|매일|평일|저녁|주말|한\s*번에)[^.!?\n\d]{0,8}(\d+)\s*분/)?.[1]
    || text.match(/(\d+)\s*분(?:만|씩|부터|밖에)/)?.[1];
  const minutes = Math.max(1, Math.min(20, Number(availableMinutes || 10)));
  const known = `${inputs.dilemma} ${(inputs.optionNotes || []).join(' ')}`.replace(/\s/g, '');
  const workCondition = ['수습 조건', '실제 담당 업무', '근무 시간', '팀의 의사결정 방식'].find((item) => !known.includes(item.replace(/\s/g, ''))) || '문서에 명시되지 않은 근무 조건';
  let tasks: Task[];
  if (/공부|학습|배우(?:고|는|기|려|면)|자격증|강의|연습|학업|대학원|진학/.test(text)) {
    tasks = [
      ['작게 시작하기', `“${goal}”와 관련된 학습 자료 한 개를 ${minutes}분 동안 살펴봅니다.`, '살펴본 자료와 실제 사용한 시간이 남아 있습니다.'],
      ['막힌 부분 확인하기', '첫 시도에서 이해되지 않은 부분 한 개를 자료의 설명이나 예제에서 찾아 확인합니다.', '막힌 부분에 대한 설명 또는 예제 하나를 찾았습니다.'],
      ['작은 결과물 만들기', '확인한 내용을 활용해 작은 예제나 연습 문제 한 개를 직접 해 봅니다.', '직접 만든 예제나 풀이 한 개가 있습니다.'],
      ['가능한 시간 정하기', '실제 일정을 보고 다음 학습을 시작할 시간 한 칸을 달력에 표시합니다.', '시작 시각이 있는 일정 하나가 있습니다.'],
      ['다른 방법 경험하기', '같은 주제를 다른 자료나 방법으로 짧게 접해 봅니다.', '두 방법 사이에서 느낀 차이 한 가지를 남겼습니다.'],
      ['이어갈 분량 정하기', '실제로 들인 시간을 기준으로 다음에 해 볼 분량을 하나 정합니다.', '다음 분량이 페이지·문제·예제 중 하나로 정해졌습니다.'],
      ['다음 단계 정하기', `“${goal}”에 도움이 된 근거를 보고 다음 주에 해 볼 방식 하나를 정합니다.`, '다음 주에 해 볼 방식과 다시 살펴볼 날짜를 정했습니다.'],
    ];
  } else if (/이직|취업|직장|회사|승진|퇴사/.test(text)) {
    tasks = [
      ['새 조건 하나 확인하기', `“${goal}”를 판단하는 데 필요한 ${workCondition} 한 가지를 공고·문서 또는 담당자에게 확인합니다.`, '조건에 대한 답변 또는 확인할 담당자를 찾았습니다.'],
      ['걱정을 질문으로 바꾸기', `“${worry}”를 확인할 수 있도록 담당자에게 보낼 질문 한 문장을 작성합니다.`, '실제 조건을 물을 수 있는 질문 한 문장이 있습니다.'],
      ['질문 전달하기', '가능한 연락 경로로 작성한 질문 한 개를 전달합니다.', '질문을 전달했거나 전달할 수 있는 창구를 확인했습니다.'],
      ['판단 근거 구분하기', '받은 자료에서 확답이 있는 조건과 추가 확인이 필요한 조건을 구분합니다.', '답변에서 확인한 조건과 미확인 조건이 구분되어 있습니다.'],
      ['현실적 부담 계산하기', inputs.constraints.budget ? `입력한 예산 “${inputs.constraints.budget}” 안에서 선택별 추가 비용 한 가지를 계산합니다.` : '선택별로 달라질 시간 또는 비용 한 가지를 실제 수치로 확인합니다.', '시간이나 비용 차이 한 가지와 그 출처를 남겼습니다.'],
      ['우선 조건 대조하기', '가장 중요한 조건 한 가지에 각 대안이 부합하는지 모은 자료로 대조합니다.', '각 대안에 대해 근거가 있는 항목과 없는 항목이 표시되어 있습니다.'],
      ['다음 단계 정하기', '모은 근거를 보고 진행·보류·추가 확인 중 지금 가능한 행동 하나를 정합니다.', '다음 행동 한 가지와 실행 날짜가 있습니다.'],
    ];
  } else if (/친구|관계|연인|가족|배우자|부모|대화/.test(text)) {
    tasks = [
      ['대화 문장 준비하기', `“${goal}”를 바탕으로 내 상황과 부탁을 담은 짧은 문장 한 개를 써 봅니다.`, '내 상황과 구체적인 부탁이 들어간 문장 하나가 있습니다.'],
      ['대화 시간 제안하기', '부담이 적은 대화 시간 한 가지를 상대에게 제안합니다.', '대화 시간을 제안했거나 가능한 연락 경로를 정했습니다.'],
      ['상대의 설명 듣기', '대화가 가능하다면 준비한 문장으로 내 상황을 전하고 상대의 설명을 듣습니다.', '상대가 실제로 말한 내용 한 가지를 남겼습니다. 대화가 어렵다면 미확인으로 둡니다.'],
      ['해석 점검하기', '상대의 실제 표현과 내가 예상했던 내용을 나누어 살펴봅니다.', '확인된 말과 내 해석이 구분되어 있습니다.'],
      ['내가 할 행동 정하기', '상대의 선택을 대신 정하지 않고 내가 할 수 있는 행동 하나를 적습니다.', '스스로 실행 여부를 정할 수 있는 행동 하나가 있습니다.'],
      ['작게 실행하기', '정한 행동을 부담이 적은 범위에서 한 번 시도합니다.', '실행 후 실제로 일어난 변화 한 가지를 남겼습니다.'],
      ['다음 대화 정하기', '관찰한 변화를 보고 추가 대화가 필요한지 정합니다.', '다음 대화 주제 또는 잠시 기다려 볼 기간이 정해졌습니다.'],
    ];
  } else {
    tasks = [
      ['판단에 필요한 자료 찾기', `“${goal}”를 위해 아직 모르는 조건 한 가지를 관련 자료나 담당자에게 확인합니다.`, '새로 확인한 조건과 출처 또는 질문할 곳을 남겼습니다.'],
      ['걱정의 조건 살펴보기', `“${worry}”가 생기는 조건 한 가지를 확인할 질문으로 바꿔 씁니다.`, '구체적인 조건으로 답할 수 있는 질문 하나가 있습니다.'],
      ['확인 질문 전달하기', '적어 둔 질문을 답할 수 있는 사람이나 공식 문의 창구에 전달합니다.', '질문을 전달했거나 확인 가능한 창구를 찾았습니다.'],
      ['작게 경험하기', '현재 목표와 관련된 활동을 되돌릴 수 있는 작은 범위에서 한 번 경험합니다.', '시도에서 실제로 관찰한 점 한 가지가 있습니다.'],
      ['현실 조건 대조하기', inputs.constraints.budget ? `“${inputs.constraints.budget}”를 기준으로 새로 확인한 비용이 감당 가능한지 대조합니다.` : '시도에 실제로 들인 시간이나 비용을 사용할 수 있는 여건과 대조합니다.', '실제 부담과 가용 여건의 차이 한 가지가 남아 있습니다.'],
      ['남은 정보 좁히기', '지금 결정을 바꿀 수 있는 미확인 조건 한 개만 남겨 확인 방법을 정합니다.', '미확인 조건 한 개와 확인 방법이 정해졌습니다.'],
      ['다음 행동 선택하기', '현재 근거로 가능한 행동 하나와 다시 살펴볼 날짜를 정합니다.', '진행·보류·추가 확인 중 다음 행동과 날짜가 있습니다.'],
    ];
  }
  const timeframe = inputs.constraints.timeframe.trim();
  const deadlineText = timeframe || inputs.dilemma;
  const dueToday = timeframe ? /오늘/.test(timeframe) : /오늘\s*(?:까지|안에)|오늘[^.!?\n]{0,20}(?:마감|답변해야|결정해야|회신해야)/.test(deadlineText);
  const dueTomorrow = timeframe ? /내일/.test(timeframe) : /내일\s*(?:까지|안에)|내일[^.!?\n]{0,20}(?:마감|답변해야|결정해야|회신해야)/.test(deadlineText);
  const deadline = dueToday ? 1 : dueTomorrow ? 2 : Number(deadlineText.match(timeframe ? /(\d+)\s*일/ : /(\d+)\s*일\s*(?:이내|안|후|남|까지)/)?.[1] || 0);
  if (deadline > 0 && deadline < 7) {
    tasks[deadline - 1] = ['기한에 맞춰 응답 정하기', '현재 모은 근거로 진행·보류·추가 확인 요청 중 가능한 응답 하나를 정합니다.', '기한에 전달할 응답 또는 추가 확인 요청을 정했습니다.'];
    const after: Task[] = [
      ['응답 이후 확인하기', '응답 후 실제로 달라진 조건 한 가지를 살펴봅니다.', '바뀐 조건이나 아직 미정인 조건을 남겼습니다.'],
      ['설명과 실제 대조하기', '처음 들었던 설명 한 가지가 실제 상황과 맞는지 확인합니다.', '설명과 실제의 일치 여부를 확인했습니다.'],
      ['필요한 도움 찾기', '새로 생긴 부담을 줄이는 데 도움이 될 사람이나 자료 하나를 찾습니다.', '연락할 곳 또는 참고할 자료 하나가 있습니다.'],
      ['작은 조정 제안하기', '관찰한 부담을 바탕으로 조정할 수 있는 조건 한 가지를 문의합니다.', '조정 가능 여부를 문의했거나 문의 문장을 준비했습니다.'],
      ['변화 기록하기', '이번 주 실제로 달라진 점 한 가지를 기록합니다.', '예상과 구분되는 실제 변화가 남아 있습니다.'],
      ['재점검 날짜 정하기', '현재 상황을 다시 살펴볼 날짜 하나를 달력에 표시합니다.', '다시 확인할 날짜가 정해졌습니다.'],
    ];
    for (let index = deadline; index < 7; index++) tasks[index] = after[index - deadline];
  }
  return {
    days: tasks.map(([title, task, completionCriteria], index): DayPlan => ({ day: index + 1, dayTitle: `${index + 1}일차: ${title}`, task, estimatedMinutes: `${minutes}분부터`, completionCriteria })),
    note: deadline > 0 && deadline < 7 ? `입력한 기한을 반영해 ${deadline}일차까지 응답을 정하고, 이후에는 실제 변화를 확인합니다.`
      : `하루 ${minutes}분부터 시작하는 초안입니다.${timeframe ? ` 실제 기한 “${timeframe}”을 우선해 날짜를 조정하세요.` : ''} 정보가 부족하면 최종 결정보다 판단 근거를 얻는 데 목적을 둡니다.`,
  };
}
